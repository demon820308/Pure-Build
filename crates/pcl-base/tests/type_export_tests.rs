use pcl_base::auth::{DeviceCodeResponse, UserProfile};
use pcl_base::java::JavaInfo;
use pcl_base::mods::ModInfo;
use pcl_base::version::VersionInfo;
use std::fs;
use std::path::Path;
use ts_rs::TS;

#[test]
fn test_export_and_verify_typescript_types() {
    let mut out = String::from("// This file was generated by [ts-rs] in pcl-base. Do not edit manually.\n\n");
    out.push_str(&format!("export {}\n\n", VersionInfo::decl()));
    out.push_str(&format!("export {}\n\n", JavaInfo::decl()));
    out.push_str(&format!("export {}\n\n", UserProfile::decl()));
    out.push_str(&format!("export {}\n\n", DeviceCodeResponse::decl()));
    out.push_str(&format!("export {}\n", ModInfo::decl()));

    let target_path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("src")
        .join("services")
        .join("types.generated.ts");

    if target_path.exists() {
        let existing = fs::read_to_string(&target_path).unwrap();
        let norm_existing = existing.replace("\r\n", "\n");
        let norm_out = out.replace("\r\n", "\n");
        assert_eq!(
            norm_existing, norm_out,
            "前端 types.generated.ts 与 Rust 后端 DTO 契约发生漂移！请重新运行测试自动同步。"
        );
    } else {
        fs::write(&target_path, &out).expect("写入 types.generated.ts 失败");
    }
}
